import { screen, waitFor, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { describe, expect, it } from 'vitest';
import type { Category, CategoryNode } from '@/features/categories/types';
import { audio } from '@/test/fixtures';
import { fail, mockApi, ok } from '@/test/mock-api';
import { buildUser, renderRoute } from '@/test/render';

const NBSP = String.fromCharCode(0xa0);

const idOf = (n: number) => `c0000000-0000-4000-8000-00000000001${n}`;

const category = (n: number, name: string, children: CategoryNode[] = []): CategoryNode => ({
  ...audio,
  id: idOf(n),
  name,
  slug: name.toLowerCase(),
  children: children.map((child) => ({ ...child, parent_id: idOf(n) })),
});

// Clothing → Men → Shirts, Audio → Headphones
const clothing = category(3, 'Clothing', [category(4, 'Men', [category(5, 'Shirts')])]);
const [men] = clothing.children;
const [shirts] = men.children;
const audioTree = category(1, 'Audio', [category(2, 'Headphones')]);
const [headphones] = audioTree.children;

/** The API answers with a flat category (no children) */
const saved = (overrides: Partial<Category>): { category: Category } => ({
  category: {
    id: headphones.id,
    parent_id: headphones.parent_id,
    name: headphones.name,
    slug: headphones.slug,
    description: null,
    created_at: headphones.created_at,
    updated_at: headphones.updated_at,
    ...overrides,
  },
});

const openCategories = (extra: Parameters<typeof mockApi>[0] = {}) => {
  const fetchMock = mockApi({
    'GET /users/me': ok({ user: buildUser({ role: 'admin' }) }),
    'GET /categories': ok({ categories: [clothing, audioTree] }),
    ...extra,
  });
  renderRoute('/admin/categories');
  return fetchMock;
};

const bodyOf = (fetchMock: ReturnType<typeof mockApi>, method: string, path: string) => {
  const call = fetchMock.mock.calls.find(
    ([url, init]) => url === `/api${path}` && init?.method === method
  );
  return call ? JSON.parse(call[1]?.body as string) : undefined;
};

describe('AdminCategoriesPage', () => {
  it('shows the tree; the deepest level cannot get subcategories', async () => {
    openCategories();

    const tree = await screen.findByRole('list', { name: 'Categories' });
    const belowMen = within(tree).getByRole('list', { name: 'Subcategories of Men' });
    expect(within(belowMen).getByText('Shirts')).toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Add a subcategory to Men' })).toBeInTheDocument();
    expect(
      screen.queryByRole('button', { name: 'Add a subcategory to Shirts' })
    ).not.toBeInTheDocument();
    expect(screen.getByRole('link', { name: 'Products in Shirts' })).toHaveAttribute(
      'href',
      `/admin/products?category=${shirts.id}`
    );
  });

  it('creates a top-level category; an empty slug is generated by the server', async () => {
    const fetchMock = openCategories({
      'POST /categories': ok(saved({ name: 'Garden', parent_id: null })),
    });

    await userEvent.click(await screen.findByRole('button', { name: 'New category' }));
    const dialog = await screen.findByRole('dialog', { name: 'New category' });
    await userEvent.type(within(dialog).getByLabelText('Name'), 'Garden');
    await userEvent.click(within(dialog).getByRole('button', { name: 'Create category' }));

    expect(await screen.findByText('Garden created')).toBeInTheDocument();
    expect(bodyOf(fetchMock, 'POST', '/categories')).toEqual({ name: 'Garden', parent_id: null });
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument());
  });

  it('starts a subcategory below the row it was added from', async () => {
    const fetchMock = openCategories({
      'POST /categories': ok(saved({ name: 'Speakers' })),
    });

    await userEvent.click(
      await screen.findByRole('button', { name: 'Add a subcategory to Audio' })
    );
    const dialog = await screen.findByRole('dialog', { name: 'New subcategory of Audio' });
    expect(within(dialog).getByLabelText('Parent category')).toHaveValue(audioTree.id);
    await userEvent.type(within(dialog).getByLabelText('Name'), 'Speakers');
    await userEvent.click(within(dialog).getByRole('button', { name: 'Create category' }));

    expect(await screen.findByText('Speakers created')).toBeInTheDocument();
    expect(bodyOf(fetchMock, 'POST', '/categories')).toEqual({
      name: 'Speakers',
      parent_id: audioTree.id,
    });
  });

  it('moves a category; its own subtree and too deep parents are not offered', async () => {
    const fetchMock = openCategories({
      [`PUT /categories/${men.id}`]: ok(
        saved({ id: men.id, name: 'Men', parent_id: audioTree.id })
      ),
    });

    await userEvent.click(await screen.findByRole('button', { name: 'Edit Men' }));
    const dialog = await screen.findByRole('dialog', { name: 'Edit Men' });
    const parent = within(dialog).getByLabelText('Parent category');
    expect(parent).toHaveValue(clothing.id);
    // Men has Shirts below it: only top-level parents keep it within 3 levels
    expect(
      within(parent)
        .getAllByRole('option')
        .map((o) => o.textContent)
    ).toEqual(['None (top level)', 'Clothing', 'Audio']);

    await userEvent.selectOptions(parent, audioTree.id);
    await userEvent.click(within(dialog).getByRole('button', { name: 'Save changes' }));

    expect(await screen.findByText('Men saved')).toBeInTheDocument();
    expect(bodyOf(fetchMock, 'PUT', `/categories/${men.id}`)).toEqual({
      name: 'Men',
      slug: 'men',
      parent_id: audioTree.id,
      // Always sent, so a removed description is cleared
      description: '',
    });
  });

  it('indents subcategories in the parent select', async () => {
    openCategories();

    await userEvent.click(await screen.findByRole('button', { name: 'New category' }));
    const parent = within(await screen.findByRole('dialog')).getByLabelText('Parent category');
    expect(within(parent).getByRole('option', { name: /Men/ }).textContent).toBe(
      `${NBSP.repeat(4)}Men`
    );
  });

  it('shows a taken name in the form', async () => {
    openCategories({
      'POST /categories': fail(409, 'A category named "Audio" already exists at this level'),
    });

    await userEvent.click(await screen.findByRole('button', { name: 'New category' }));
    const dialog = await screen.findByRole('dialog');
    await userEvent.type(within(dialog).getByLabelText('Name'), 'Audio');
    await userEvent.click(within(dialog).getByRole('button', { name: 'Create category' }));

    expect(await within(dialog).findByRole('alert')).toHaveTextContent('already exists');
  });

  it('deletes after confirmation and explains why a category cannot be deleted', async () => {
    const fetchMock = openCategories({
      [`DELETE /categories/${shirts.id}`]: ok(),
      [`DELETE /categories/${headphones.id}`]: fail(
        409,
        'Category still has products (including inactive ones). Move them first.'
      ),
    });

    await userEvent.click(await screen.findByRole('button', { name: 'Delete Shirts' }));
    let dialog = await screen.findByRole('alertdialog', { name: 'Delete Shirts?' });
    await userEvent.click(within(dialog).getByRole('button', { name: 'Delete' }));
    expect(await screen.findByText('Shirts deleted')).toBeInTheDocument();
    expect(
      fetchMock.mock.calls.some(
        ([u, init]) => u === `/api/categories/${shirts.id}` && init?.method === 'DELETE'
      )
    ).toBe(true);

    await userEvent.click(screen.getByRole('button', { name: 'Delete Headphones' }));
    dialog = await screen.findByRole('alertdialog', { name: 'Delete Headphones?' });
    await userEvent.click(within(dialog).getByRole('button', { name: 'Delete' }));
    expect(await screen.findByText(/still has products/)).toBeInTheDocument();
  });
});
